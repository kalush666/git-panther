import { scaleTokens, themedTokens, type ThemeName } from './tokens.ts';

export const CSS_VAR_PREFIX = '--gp-';

export function cssVar(name: string): string {
  return `var(${CSS_VAR_PREFIX}${name})`;
}

function declarations(entries: ReadonlyArray<readonly [string, string]>): string {
  return entries.map(([name, value]) => `  ${CSS_VAR_PREFIX}${name}: ${value};`).join('\n');
}

function themeDeclarations(theme: ThemeName): string {
  const entries = Object.entries(themedTokens).map(
    ([name, values]) => [name, values[theme]] as const,
  );
  return `  color-scheme: ${theme};\n${declarations(entries)}`;
}

/**
 * Renders all tokens as CSS custom properties. Dark is the default theme;
 * `data-theme="light"` on the root element switches to light.
 */
export function renderTokensCss(): string {
  return [
    '/* Generated by @git-panther/design-tokens — do not edit. Run `pnpm tokens`. */',
    `:root {\n${declarations(Object.entries(scaleTokens))}\n}`,
    `:root,\n:root[data-theme='dark'] {\n${themeDeclarations('dark')}\n}`,
    `:root[data-theme='light'] {\n${themeDeclarations('light')}\n}`,
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n    ${CSS_VAR_PREFIX}duration-fast: 0ms;\n    ${CSS_VAR_PREFIX}duration-base: 0ms;\n  }\n}`,
    '',
  ].join('\n\n');
}
